async function main() {
  const prisma = new PrismaClient({
    adapter: new PrismaPg({ connectionString: url }),
  });
  try {
    for (const u of UPDATES) {
      const result = await prisma.quest.updateMany({
        where: { title: u.title },
        data: {
          description: u.description,
          price: u.price,
          imageAlt: u.imageAlt,
          // image intentionally untouched
        },
      });
      console.log(`ok ${u.title}: updated ${result.count} row(s), price=${u.price}`);
    }
  } finally {
    await prisma.$disconnect();
  }
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
